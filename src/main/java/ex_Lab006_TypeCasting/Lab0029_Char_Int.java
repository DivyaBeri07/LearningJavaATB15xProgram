package ex_Lab006_TypeCasting;

public class Lab0029_Char_Int {
    //Widening Casting (Implicit / Automatic)-> Smaller data type to larger data type
    // example:int to double or char to int
    public static void main(String[] args) {

        char ch = 'A';
        int a = ch;

        System.out.println(ch);
        System.out.println(a);
    }
}
